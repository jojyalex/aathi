#!/usr/bin/env python3
"""Build lessons: Malayalam audio + word timings + lessons/<id>/data.js, and the catalog lessons/index.js.

Usage:  python3 tools/build_lesson.py              build every lessons/*/lesson.json (only changed lines re-made)
        python3 tools/build_lesson.py u1-l1-adukkala [more ids]
        python3 tools/build_lesson.py --index      only rewrite lessons/index.js
Needs:  pip install edge-tts   (internet, Microsoft's ml-IN neural voices)
"""
import asyncio, glob, hashlib, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_story import align, synth  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LDIR = os.path.join(ROOT, 'lessons')
AATHI = {'id': 'u3-l3-aathi', 'unit': 3, 'unitMl': 'നൽകുകിൽ നേടാം', 'unitEn': 'Give, and you gain', 'order': 3,
         'title': 'ഒരു സ്വപ്നമുണ്ടായിരുന്നു...', 'titleEn': 'There Was a Dream (from Aathi)', 'pages': '48–54', 'kind': 'story',
         'level': 'hard', 'icon': '🌊', 'days': 15, 'builtin': True}
META = ('id', 'unit', 'unitMl', 'unitEn', 'order', 'title', 'titleEn', 'pages', 'kind', 'author', 'level', 'icon')


async def build(lid, force=False):
    src_path = os.path.join(LDIR, lid, 'lesson.json')
    L = json.load(open(src_path, encoding='utf-8'))
    adir = os.path.join(LDIR, lid, 'audio')
    os.makedirs(adir, exist_ok=True)
    cpath = os.path.join(LDIR, lid, '.audio_cache.json')
    cache = {} if force or not os.path.exists(cpath) else json.load(open(cpath, encoding='utf-8'))
    sents, n = [], 0
    for sc in L['scenes']:
        for row in sc['sents']:
            n += 1
            sents.append({'id': f's{n:03d}', 'scene': sc['id'], 'sp': row[0], 'ml': row[1], 'en': row[2], 'fx': row[3] if len(row) > 3 else ''})
    sem = asyncio.Semaphore(4)
    made = 0

    async def one(s):
        nonlocal made
        sp = L['speakers'][s['sp']]
        key = hashlib.sha1(json.dumps([s['ml'], sp['voice'], sp['rate'], sp['pitch']], ensure_ascii=False).encode()).hexdigest()
        path = os.path.join(adir, s['id'] + '.mp3')
        c = cache.get(s['id'])
        if not (c and c['key'] == key and os.path.exists(path)):
            async with sem:
                for attempt in range(4):
                    try:
                        marks, dur = await synth(s['ml'], sp, path)
                        break
                    except Exception:
                        if attempt == 3:
                            raise
                        await asyncio.sleep(3 * (attempt + 1))
            c = cache[s['id']] = {'key': key, 'marks': marks, 'dur': dur}
            made += 1
        words, exact = align(s['ml'].split(), c['marks'], c['dur'])
        if not exact:
            print(f'  ! {lid} {s["id"]}: word timing estimated')
        s.update(audio=f'lessons/{lid}/audio/{s["id"]}.mp3', dur=round(c['dur'], 2), words=words)

    await asyncio.gather(*(one(s) for s in sents))
    json.dump(cache, open(cpath, 'w', encoding='utf-8'), ensure_ascii=False)
    for old in glob.glob(os.path.join(adir, 's*.mp3')):  # drop audio of removed lines
        if os.path.basename(old)[:-4] not in {s['id'] for s in sents}:
            os.remove(old)

    days = []
    for i, d in enumerate(L['plan']):
        steps = []
        for st in d['steps']:
            st = dict(st)
            if st['t'] == 'write': st.setdefault('k', 'main')
            if st['t'] == 'retell': st.setdefault('name', 'final'); st.setdefault('parts', ['F'])
            steps.append(st)
        days.append({'n': i + 1, 'title': d['title'], 'ml': d['ml'], 'icon': d.get('icon', '⭐'), 'mode': d.get('mode', ''), 'steps': steps})
    data = {k: L[k] for k in META if k in L}
    data.update({
        'days': len(days), 'summaryEn': L['summaryEn'],
        'STORY': {'title': L['title'], 'credit': f"{L.get('titleEn', '')}{' — ' + L['author'] if L.get('author') else ''} (Kerala Padavali, Class 6, pages {L.get('pages', '')})",
                  'speakers': {k: {kk: v[kk] for kk in ('name', 'ml', 'emoji')} for k, v in L['speakers'].items()},
                  'scenes': [{k: sc[k] for k in ('id', 'title', 'ml', 'art', 'book') if k in sc} for sc in L['scenes']],
                  'sents': sents},
        'WORDS': [dict(w, id=f"{lid}:{w['id']}") for w in L['words']],
        'COMP': [dict(q, id=f'Q{i + 1}') for i, q in enumerate(L['quiz'])],
        'BUILD': L['build'], 'RETELL': {'F': L['retell']},
        'WRITE': {'main': dict(L['write'], key=f'{lid}:write')},
        'INFO': {}, 'DAYS': days,
    })
    with open(os.path.join(LDIR, lid, 'data.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build_lesson.py from lesson.json - do not edit. */\n')
        f.write(f'(window.LESSONS=window.LESSONS||{{}})[{json.dumps(lid)}]=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    mins = sum(s['dur'] for s in sents) / 60
    print(f'✓ {lid}: {len(sents)} lines ({made} new audio), {mins:.1f} min, {len(days)} days')


def write_index():
    cat = [AATHI]
    for p in sorted(glob.glob(os.path.join(LDIR, '*', 'lesson.json'))):
        lid = os.path.basename(os.path.dirname(p))
        if not os.path.exists(os.path.join(LDIR, lid, 'data.js')):
            continue
        L = json.load(open(p, encoding='utf-8'))
        e = {k: L[k] for k in META if k in L}
        e['days'] = len(L['plan'])
        e['lines'] = sum(len(s['sents']) for s in L['scenes'])
        cat.append(e)
    cat.sort(key=lambda e: (e['unit'], e['order']))
    with open(os.path.join(LDIR, 'index.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build_lesson.py - list of lessons. */\nvar CATALOG = ' + json.dumps(cat, ensure_ascii=False, indent=1) + ';\n')
    print(f'✓ lessons/index.js: {len(cat)} lessons')


async def main(args):
    force = '--force' in args
    ids = [a for a in args if not a.startswith('--')]
    if '--index' not in args:
        if not ids:
            ids = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(LDIR, '*', 'lesson.json')))
        for lid in ids:
            await build(lid, force)
    write_index()


if __name__ == '__main__':
    asyncio.run(main(sys.argv[1:]))
